import asyncio
from typing import AsyncGenerator, Dict, Any, Optional
from agents.state import AgentState, SSEEvent
from agents.supervisor import classify_intent, synthesize_explanation
from agents.specialists.air import air_specialist_node
from agents.specialists.traffic import traffic_specialist_node
from agents.specialists.routing import routing_specialist_node
from agents.specialists.policy import policy_specialist_node
from agents.specialists.advisory import advisory_specialist_node

class ClearPathAgentWorkflow:
    """
    Multi-Agent LangGraph-compatible workflow with event streaming and human approval gating.
    """
    async def run_stream(
        self,
        query: str,
        preset_id: Optional[str] = None,
        vehicle_type: str = "car",
        depart_at: Optional[str] = None,
        balance: float = 0.5
    ) -> AsyncGenerator[SSEEvent, None]:
        state = AgentState(
            messages=[{"role": "user", "content": query}],
            preset_id=preset_id,
            vehicle_type=vehicle_type,
            depart_at=depart_at,
            balance=balance
        )
        
        # 1. Supervisor Intent Classification
        intent = classify_intent(query, vehicle_type)
        state.intent = intent
        
        start_event = SSEEvent(
            event="agent_start",
            data={"agent": "supervisor", "intent": intent}
        )
        state.events.append(start_event)
        yield start_event
        await asyncio.sleep(0.05)

        # 2. Invoke Specialists
        if intent == "route_planning":
            await routing_specialist_node(state)
            await air_specialist_node(state)
            await advisory_specialist_node(state)
        elif intent == "truck_routing":
            await routing_specialist_node(state)
            await traffic_specialist_node(state)
        elif intent == "policy_proposal":
            await air_specialist_node(state)
            await traffic_specialist_node(state)
            await policy_specialist_node(state)
        elif intent == "air_forecast":
            await air_specialist_node(state)
        elif intent == "citizen_advisory":
            await advisory_specialist_node(state)
            await air_specialist_node(state)
        else:
            await routing_specialist_node(state)

        # Yield events generated by specialists
        for ev in state.events[1:]:
            yield ev
            await asyncio.sleep(0.02)

        # 3. Supervisor Synthesizes Explanation
        explanation = synthesize_explanation(state, query)
        state.final_message = explanation

        # Emit token chunks
        words = explanation.split(" ")
        for i in range(0, len(words), 8):
            chunk = " ".join(words[i:i+8]) + " "
            yield SSEEvent(
                event="token",
                data={"text": chunk}
            )
            await asyncio.sleep(0.01)

        # 4. Final Event
        final_payload: Dict[str, Any] = {
            "message": explanation,
            "intent": intent,
            "vehicle_type": vehicle_type
        }
        if state.routes:
            final_payload["routes"] = state.routes
        if state.hotspots:
            final_payload["hotspots"] = state.hotspots
        if state.pending_proposal_id:
            final_payload["pending_proposal_id"] = state.pending_proposal_id

        yield SSEEvent(
            event="final",
            data=final_payload
        )

workflow_engine = ClearPathAgentWorkflow()
